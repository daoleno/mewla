// Writes ui/icons/svg/<name>.svg for every Mewla glyph and ui/icons/assets.ts that imports them.
// Run after changing ui/icons/glyphs.ts: `bun client/scripts/gen-icons.ts`.
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { MEWLA_GLYPHS } from "../ui/icons/glyphs";

const dir = join(import.meta.dir, "../ui/icons");
const svgDir = join(dir, "svg");
mkdirSync(svgDir, { recursive: true });
for (const file of readdirSync(svgDir)) if (file.endsWith(".svg")) rmSync(join(svgDir, file));
const names = Object.keys(MEWLA_GLYPHS).sort();
for (const name of names) {
  const glyph = MEWLA_GLYPHS[name as keyof typeof MEWLA_GLYPHS];
  const strokes = glyph.strokes.map((d) => `<path d="${d}" fill="none" stroke="#000" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"/>`);
  const fills = (glyph.fills ?? []).map((d) => `<path d="${d}" fill="#000" fill-rule="evenodd"/>`);
  writeFileSync(join(svgDir, `${name}.svg`), `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">${[...strokes, ...fills].join("")}</svg>\n`);
}
const ident = (name: string) => "i_" + name.replace(/[^a-zA-Z0-9]/g, "_");
writeFileSync(
  join(dir, "assets.ts"),
  `// Generated by client/scripts/gen-icons.ts from glyphs.ts; do not edit.\n${names.map((n) => `import ${ident(n)} from "./svg/${n}.svg";`).join("\n")}\n\nexport const ICON_ASSETS = {\n${names.map((n) => `  ${JSON.stringify(n)}: ${ident(n)},`).join("\n")}\n} as const;\n`,
);
console.log(`${names.length} icons`);
