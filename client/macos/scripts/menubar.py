#!/usr/bin/env python3
"""The menu bar cat's images (client/ui/mac/assets/menubar) from the design's, 1:1 (DESIGN-MAC.md §2.1, P3).

    python3 -I client/macos/scripts/menubar.py <design>/assets/menubar

Takes final/ and frames/ (timeline.json) as the design made them. A template image (the face, hollow, the update
dot, Brain's arc, the nod) stays an SVG: macOS draws an SVG status item as a template, in the menu bar's colour. An
image with the seal's red (needs you, and its arrival: the lift and the stamp) is made a PNG at 2x with rsvg-convert,
one per menu bar appearance, since a template would lose the red. Writes client/ui/mac/menubarImages.ts: the
images imported, and each clip's frames, frame time and whether it loops.
"""
import json
import pathlib
import shutil
import subprocess
import sys

src = pathlib.Path(sys.argv[1])
out = pathlib.Path(__file__).resolve().parents[2] / "ui" / "mac" / "assets" / "menubar"
if out.exists():
    shutil.rmtree(out)
out.mkdir(parents=True)


def take(rel, template):
    """Copies a template SVG, or rasterizes a coloured one; returns the asset's file name."""
    source = src / rel
    name = rel.replace("final/", "").replace("/", "-")
    if template:
        shutil.copyfile(source, out / name)
        return name
    png = name.removesuffix(".svg") + ".png"
    subprocess.run(["rsvg-convert", "-z", "2", "-o", str(out / png), str(source)], check=True)
    return png


timeline = json.loads((src / "frames" / "timeline.json").read_text())
images = {
    "quiet": take("final/quiet.svg", True),
    "offline": take("final/offline.svg", True),
    "update": take("final/update.svg", True),
    "needs-light": take("final/needs-light.svg", False),
    "needs-dark": take("final/needs-dark.svg", False),
}
clips = {}
for key, clip in timeline["clips"].items():
    template = clip["template"]
    fps = clip.get("fps", timeline["fps"])
    clips[key] = {
        "frames": [take(f"frames/{frame}", template) for frame in clip["frames"]],
        "frame_ms": round(1000 / fps),
        "loop": bool(clip.get("loop")),
        "then": take(clip["then"], template) if "then" in clip else None,
    }
names = {}


def ref(file):
    """The import's identifier for an asset file."""
    if file not in names:
        names[file] = "i" + "".join(part.title() for part in file.rsplit(".", 1)[0].replace("-", " ").split())
    return names[file]


body = ["export const MENU_BAR_IMAGES = {"]
body += [f"  {json.dumps(key)}: {ref(file)}," for key, file in images.items()]
body += ["} as const;", "", "export const MENU_BAR_CLIPS = {"]
for key, clip in clips.items():
    frames = ", ".join(ref(f) for f in clip["frames"])
    body.append(f"  {json.dumps(key)}: {{ frames: [{frames}], frameMs: {clip['frame_ms']}, loop: {str(clip['loop']).lower()} }},")
body += ["} as const;"]
head = ["// Generated by client/macos/scripts/menubar.py from the design's menu bar assets; do not edit."]
head += [f'import {name} from "./assets/menubar/{file}";' for file, name in names.items()]
ts = out.parents[1] / "menubarImages.ts"
ts.write_text("\n".join(head + [""] + body) + "\n")
print(ts)
