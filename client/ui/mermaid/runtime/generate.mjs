#!/usr/bin/env bun
// Writes ../mermaidSource.ts: mermaid's own browser build (dist/mermaid.min.js) as a string constant, which the
// diagram engine's WebView document runs (`../engine.ts`): it loads no remote script, so diagrams draw offline.
// mermaid comes from the repository's installed `mermaid` (pinned in the root package.json).
//
//   bun client/ui/mermaid/runtime/generate.mjs           # rewrite
//   bun client/ui/mermaid/runtime/generate.mjs --check   # fail if stale

import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "../../../..");
// A worktree without node_modules can name a checkout's copy: MEWLA_MERMAID_DIR=<…/node_modules/mermaid>.
const packageDir = process.env.MEWLA_MERMAID_DIR || dirname(createRequire(join(repo, "package.json")).resolve("mermaid/package.json"));
const { version, license } = JSON.parse(readFileSync(join(packageDir, "package.json"), "utf8"));
const original = readFileSync(join(packageDir, "dist", "mermaid.min.js"), "utf8");
// Its few characters past ASCII (all in regex and string literals) written as \uXXXX: an ASCII string is kept in
// 8 bits by QuickJS, where one other character makes the whole 5 MB 16 bits (11 MB of bytecode instead of 5.5).
const code = original.replace(/[^\x00-\x7f]/g, (ch) => `\\u${ch.charCodeAt(0).toString(16).padStart(4, "0")}`);
if (/<\/script/i.test(code)) throw new Error("mermaid.min.js contains </script; it cannot be inlined as it is");
// The checksum is the upstream file's, as published.
const sha256 = createHash("sha256").update(original).digest("hex");
const output = [
  `// Generated by runtime/generate.mjs from mermaid ${version} (${license}), dist/mermaid.min.js with non-ASCII escaped. Do not edit.`,
  `export const MERMAID_VERSION = ${JSON.stringify(version)};`,
  `export const MERMAID_LICENSE = ${JSON.stringify(license)};`,
  `export const MERMAID_SHA256 = ${JSON.stringify(sha256)};`,
  `export const MERMAID_SOURCE = ${JSON.stringify(code)};`,
  "",
].join("\n");
const path = join(here, "..", "mermaidSource.ts");
if (process.argv.includes("--check")) {
  if (!existsSync(path) || readFileSync(path, "utf8") !== output) {
    console.error(`${path} is stale: run bun client/ui/mermaid/runtime/generate.mjs`);
    process.exit(1);
  }
  console.log(`mermaidSource.ts is current (mermaid ${version}, sha256 ${sha256})`);
} else {
  writeFileSync(path, output);
  console.log(`wrote ${path} (mermaid ${version}, ${code.length} bytes, sha256 ${sha256})`);
}
