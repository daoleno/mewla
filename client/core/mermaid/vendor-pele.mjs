#!/usr/bin/env bun
// Writes ./pele.js: Pele's own build (dist/pele.js, one self-contained module with no imports) from the `pele`
// package pinned in the root package.json, unchanged but for a header. Pele draws Mermaid diagrams to an SVG
// string with no DOM, so it runs in the app itself (QuickJS) and in `bun test`.
//
//   bun client/core/mermaid/vendor-pele.mjs           # rewrite
//   bun client/core/mermaid/vendor-pele.mjs --check   # fail if stale

import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "../../..");
// A worktree without node_modules can name a checkout's copy: MEWLA_PELE_DIR=<…/node_modules/pele>.
const packageDir = process.env.MEWLA_PELE_DIR || dirname(createRequire(join(repo, "package.json")).resolve("pele/package.json"));
const { version, license } = JSON.parse(readFileSync(join(packageDir, "package.json"), "utf8"));
const code = readFileSync(join(packageDir, "dist", "pele.js"), "utf8");
if (/^\s*import\s|\bimport\(/m.test(code)) throw new Error("pele's dist/pele.js imports a module; vendor its dependencies too");
const sha256 = createHash("sha256").update(code).digest("hex");
const output = `// Generated by vendor-pele.mjs from pele ${version} (${license}, github.com/obsidianmd/pele) dist/pele.js, sha256 ${sha256}. Do not edit.\n// @ts-nocheck\n${code}`;
const path = join(here, "pele.js");
if (process.argv.includes("--check")) {
  if (!existsSync(path) || readFileSync(path, "utf8") !== output) {
    console.error(`${path} is stale: run bun client/core/mermaid/vendor-pele.mjs`);
    process.exit(1);
  }
  console.log(`pele.js is current (pele ${version}, sha256 ${sha256})`);
} else {
  writeFileSync(path, output);
  console.log(`wrote ${path} (pele ${version}, ${code.length} bytes, sha256 ${sha256})`);
}
