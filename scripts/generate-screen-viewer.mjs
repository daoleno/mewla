#!/usr/bin/env bun
// Regenerate the offline Screen viewer (app/components/screen/runtime plus
// noVNC) from the installed `@novnc/novnc` devDependency, which
// app/package.json pins.
//
// Two outputs share one viewer:
// - screenViewerSource.js: the native WebView document's script as a string
//   constant, since the WebView loads no remote scripts.
// - screenViewerRuntime.js: an ES module the web build imports directly; the
//   web UI's CSP forbids inline and srcdoc scripts.
// noVNC 1.7 probes H.264 support with a top-level await, which Metro cannot
// bundle; the probe is rewritten to settle in the background (the viewer never
// requests H.264).
//
// Usage:
//   bun install
//   bun run screen:generate           # rewrite both files
//   bun run screen:generate --check   # fail if either file is stale

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(root, "app", "package.json"));
const packageDir = dirname(require.resolve("@novnc/novnc/package.json"));
const { version, license } = JSON.parse(readFileSync(join(packageDir, "package.json"), "utf8"));

const TOP_LEVEL_AWAIT = "supportsWebCodecsH264Decode = await _checkWebCodecsH264DecodeSupport();";
const noTopLevelAwait = {
  name: "novnc-no-top-level-await",
  setup(build) {
    build.onLoad({ filter: /novnc[\\/]core[\\/]util[\\/]browser\.js$/ }, async (args) => {
      const source = readFileSync(args.path, "utf8");
      if (!source.includes(TOP_LEVEL_AWAIT)) throw new Error("noVNC browser.js changed; update the top-level await patch");
      return {
        loader: "js",
        contents: source.replace(TOP_LEVEL_AWAIT, "_checkWebCodecsH264DecodeSupport().then((supported) => { supportsWebCodecsH264Decode = supported; });"),
      };
    });
  },
};

async function bundle(entry) {
  const result = await Bun.build({
    entrypoints: [join(root, "app/components/screen/runtime", entry)],
    target: "browser",
    format: "esm",
    minify: true,
    plugins: [noTopLevelAwait],
  });
  if (!result.success) {
    for (const log of result.logs) console.error(log);
    process.exit(1);
  }
  const code = await result.outputs[0].text();
  if (code.includes("await _checkWebCodecsH264DecodeSupport")) throw new Error(`${entry}: top-level await survived`);
  return code;
}

const runtime = await bundle("bootstrap.js");
const module = await bundle("viewer.js");
const sha256 = createHash("sha256").update(runtime).update(module).digest("hex");
const banner = `// Generated by scripts/generate-screen-viewer.mjs from noVNC ${version} (${license}). Do not edit.\n`;

const outputs = {
  "app/components/screen/screenViewerSource.js":
    `${banner}export const SCREEN_VIEWER_SOURCE = ${JSON.stringify(runtime)};\n`,
  "app/components/screen/screenViewerRuntime.js": `${banner}${module}\n`,
  "app/components/screen/screenViewerMeta.ts": [
    `export const NOVNC_VERSION = ${JSON.stringify(version)};`,
    `export const NOVNC_LICENSE = ${JSON.stringify(license)};`,
    `export const SCREEN_VIEWER_SHA256 = ${JSON.stringify(sha256)};`,
    "",
  ].join("\n"),
};

const check = process.argv.includes("--check");
let stale = false;
for (const [relative, content] of Object.entries(outputs)) {
  const path = join(root, relative);
  let current = "";
  try {
    current = readFileSync(path, "utf8");
  } catch {}
  if (current === content) continue;
  if (check) {
    console.error(`stale: ${relative} (run: bun run screen:generate)`);
    stale = true;
  } else {
    writeFileSync(path, content);
    console.log(`wrote ${relative}`);
  }
}
if (stale) process.exit(1);
console.log(`screen viewer (noVNC ${version}) sha256 ${sha256}: native ${runtime.length} bytes, web ${module.length} bytes`);
