package setup

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"github.com/BurntSushi/toml"
	"github.com/daoleno/mewla/daemon/work"
)

type executorFile struct {
	Executors []work.Executor `toml:"executors"`
}

type configWriteRequest struct {
	Path     string
	Selected []selectedExecutor
	Now      time.Time
}

type selectedExecutor struct {
	ID       string
	Provider string
	Existing work.Executor
}

type configWriteResult struct {
	Path       string
	BackupPath string
}

func writeExecutorsConfig(req configWriteRequest) (configWriteResult, error) {
	if strings.TrimSpace(req.Path) == "" {
		return configWriteResult{}, fmt.Errorf("executors path required")
	}
	if req.Now.IsZero() {
		req.Now = time.Now().UTC()
	}

	existingByName := map[string]work.Executor{}
	var existingRaw []byte
	if raw, err := os.ReadFile(req.Path); err == nil {
		existingRaw = raw
		var parsed executorFile
		if unmarshalErr := toml.Unmarshal(raw, &parsed); unmarshalErr == nil {
			for _, executor := range parsed.Executors {
				name := strings.TrimSpace(executor.Name)
				if name == "" {
					continue
				}
				existingByName[name] = executor
			}
		}
	} else if !os.IsNotExist(err) {
		return configWriteResult{}, err
	}

	outByName := map[string]work.Executor{}
	// Preserve unrelated existing file entries.
	for name, executor := range existingByName {
		outByName[name] = executor
	}
	// Apply the selected executors.
	for _, selected := range req.Selected {
		existing := selected.Existing
		if prev, ok := existingByName[selected.ID]; ok {
			existing = prev
		}
		command, kind := commandForProvider(selected.Provider, selected.ID, existing.Command)
		entry := work.Executor{
			Name:    selected.ID,
			Command: command,
			Kind:    kind,
			Runtime: existing.Runtime,
			// A separate sign-in survives setup being run again.
			ConfigDir: existing.ConfigDir,
		}
		if entry.Kind == "" {
			entry.Kind = existing.Kind
		}
		outByName[selected.ID] = entry
	}

	names := make([]string, 0, len(outByName))
	for name := range outByName {
		names = append(names, name)
	}
	sort.Strings(names)

	file := executorFile{
		Executors: make([]work.Executor, 0, len(names)),
	}
	for _, name := range names {
		file.Executors = append(file.Executors, outByName[name])
	}

	body, err := renderExecutorsTOML(file)
	if err != nil {
		return configWriteResult{}, err
	}

	result := configWriteResult{Path: req.Path}
	if err := os.MkdirAll(filepath.Dir(req.Path), 0o700); err != nil {
		return result, err
	}
	if len(existingRaw) > 0 {
		backup := req.Path + ".bak." + req.Now.UTC().Format("20060102T150405Z")
		if err := os.WriteFile(backup, existingRaw, 0o600); err != nil {
			return result, fmt.Errorf("backup executors.toml: %w", err)
		}
		result.BackupPath = backup
	}

	tmp := req.Path + ".tmp." + fmt.Sprintf("%d", req.Now.UnixNano())
	if err := os.WriteFile(tmp, body, 0o600); err != nil {
		return result, err
	}
	if err := os.Rename(tmp, req.Path); err != nil {
		_ = os.Remove(tmp)
		return result, err
	}
	return result, nil
}

func renderExecutorsTOML(file executorFile) ([]byte, error) {
	var b strings.Builder
	b.WriteString("# Generated by mewla setup. Review before use.\n")
	b.WriteString("# Agents run with full authority: no approvals, no sandbox.\n")
	b.WriteString("# Restart mewla after changing executor definitions or commands.\n")
	b.WriteString("# Brain picks each Worker's executor, model and reasoning from its routing.md.\n\n")
	for _, executor := range file.Executors {
		b.WriteString("[[executors]]\n")
		b.WriteString("name = \"" + escapeTOMLString(executor.Name) + "\"\n")
		b.WriteString("command = \"" + escapeTOMLString(executor.Command) + "\"\n")
		if kind := strings.TrimSpace(executor.Kind); kind != "" {
			b.WriteString("kind = \"" + escapeTOMLString(kind) + "\"\n")
		}
		if runtime := strings.TrimSpace(executor.Runtime); runtime != "" {
			b.WriteString("runtime = \"" + escapeTOMLString(runtime) + "\"\n")
		}
		if dir := strings.TrimSpace(executor.ConfigDir); dir != "" {
			b.WriteString("config_dir = \"" + escapeTOMLString(dir) + "\"\n")
		}
		b.WriteString("\n")
	}
	return []byte(b.String()), nil
}

func escapeTOMLString(value string) string {
	replacer := strings.NewReplacer(
		`\`, `\\`,
		`"`, `\"`,
	)
	return replacer.Replace(value)
}

// AddExecutor adds or replaces one executor in the file at path, keeping every
// other entry, and backs the old file up. It returns the backup path ("" when
// there was no file).
func AddExecutor(path string, entry work.Executor, now time.Time) (string, error) {
	if strings.TrimSpace(path) == "" {
		return "", fmt.Errorf("executors path required")
	}
	if now.IsZero() {
		now = time.Now()
	}
	var file executorFile
	raw, err := os.ReadFile(path)
	switch {
	case err == nil:
		if err := toml.Unmarshal(raw, &file); err != nil {
			return "", fmt.Errorf("read %s: %w", path, err)
		}
	case !os.IsNotExist(err):
		return "", err
	}
	replaced := false
	for i := range file.Executors {
		if strings.TrimSpace(file.Executors[i].Name) == entry.Name {
			file.Executors[i], replaced = entry, true
		}
	}
	if !replaced {
		file.Executors = append(file.Executors, entry)
	}
	body, err := renderExecutorsTOML(file)
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return "", err
	}
	backup := ""
	if len(raw) > 0 {
		backup = path + ".bak." + now.UTC().Format("20060102T150405Z")
		if err := os.WriteFile(backup, raw, 0o600); err != nil {
			return "", fmt.Errorf("backup executors.toml: %w", err)
		}
	}
	tmp := path + ".tmp." + fmt.Sprintf("%d", now.UnixNano())
	if err := os.WriteFile(tmp, body, 0o600); err != nil {
		return backup, err
	}
	if err := os.Rename(tmp, path); err != nil {
		_ = os.Remove(tmp)
		return backup, err
	}
	return backup, nil
}
