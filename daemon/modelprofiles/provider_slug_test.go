// TestProviderSlugForKeepsSharedIDPrefixDistinct is the regression for the
// 1-in-4096 collision that surfaced in CI as
// `model profile revision conflict: provider slug "provider-conn-fb0"`.
// The two ids below share their first eight characters ("conn_fb0"), which is
// exactly where the old eight-character truncation stopped.
func TestProviderSlugForKeepsSharedIDPrefixDistinct(t *testing.T) {
	firstID := "conn_fb0a1b2c3d4e5f60"
	secondID := "conn_fb0a1b2c3d4e5f61"
	if firstID[:8] != secondID[:8] {
		t.Fatalf("fixture ids must share their first eight characters: %q %q", firstID[:8], secondID[:8])
	}

	first := ProviderSlugFor("Acme", firstID)
	second := ProviderSlugFor("Acme", secondID)
	if first == second {
		t.Fatalf("shared id prefix produced duplicate slug %q", first)
	}
	for _, slug := range []string{first, second} {
		if err := ValidateProviderSlug(slug); err != nil {
			t.Fatalf("generated slug %q is invalid: %v", slug, err)
		}
	}
	// The whole random tail must survive, not just three hex digits.
	if !strings.Contains(first, "fb0a1b2c3d4e5f60") || !strings.Contains(second, "fb0a1b2c3d4e5f61") {
		t.Fatalf("slug dropped connection identity: %q %q", first, second)
	}
}

// TestProviderSlugForKeepsIDWhenNameIsLong proves the display name is what
// gets shortened to fit the 48-character slug, never the identity suffix.
func TestProviderSlugForKeepsIDWhenNameIsLong(t *testing.T) {
	longName := strings.Repeat("verylongname", 6) // 72 characters, over MaxProviderNameLength
	id := "conn_0123456789abcdef"
	slug := ProviderSlugFor(longName, id)
	if err := ValidateProviderSlug(slug); err != nil {
		t.Fatalf("generated slug %q is invalid: %v", slug, err)
	}
	if len(slug) > maxProviderSlugLength {
		t.Fatalf("slug length %d exceeds %d: %q", len(slug), maxProviderSlugLength, slug)
	}
	if !strings.HasSuffix(slug, "conn-0123456789abcdef") {
		t.Fatalf("long name truncated the identity suffix: %q", slug)
	}
}

// TestStoreCreateAllowsSharedIDPrefix is the end-to-end shape of the user bug:
// two connections whose ids share their first eight characters, and whose
// display names normalize to the same slug base, must both be created.
func TestStoreCreateAllowsSharedIDPrefix(t *testing.T) {
	path := filepath.Join(t.TempDir(), "model-profiles.toml")
	store, err := NewStore(path)
	if err != nil {
		t.Fatal(err)
	}

	first := codexResponsesProfile("conn_fb0aaa0000000001", "gpt-5", "up-a")
	second := codexResponsesProfile("conn_fb0bbb0000000002", "gpt-5", "up-b")
	// Distinct names (so the duplicate-name guard does not fire) that fold to
	// the same slug base, plus ids sharing the same eight-character prefix.
	first.Name = "Acme Inc"
	second.Name = "Acme  Inc"

	if _, err := store.Create(first, 0); err != nil {
		t.Fatalf("create first connection: %v", err)
	}
	if _, err := store.Create(second, 1); err != nil {
		t.Fatalf("create second connection with shared id prefix: %v", err)
	}

	storedFirst, err := store.Get(first.ID)
	if err != nil {
		t.Fatal(err)
	}
	storedSecond, err := store.Get(second.ID)
	if err != nil {
		t.Fatal(err)
	}
	if storedFirst.Slug == "" || storedSecond.Slug == "" {
		t.Fatalf("created connections missing slugs: %q %q", storedFirst.Slug, storedSecond.Slug)
	}
	if strings.EqualFold(storedFirst.Slug, storedSecond.Slug) {
		t.Fatalf("connections collided on slug %q", storedFirst.Slug)
	}
}

// TestStoreLoadPreservesPersistedSlug proves the durable format change is
// backwards compatible: a slug already written to disk keeps resolving and is
// never regenerated by a plain load.
func TestStoreLoadPreservesPersistedSlug(t *testing.T) {
	profile := codexResponsesProfile("conn_fb0aaa0000000001", "gpt-5", "up-a")
	profile.Name = "Acme"
	profile.Slug = "provider-conn-fb0" // legacy slug from before the fix
	var data bytes.Buffer
	if err := toml.NewEncoder(&data).Encode(fileDocument{Revision: 3, Profiles: []Profile{profile}}); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(t.TempDir(), "model-profiles.toml")
	if err := os.WriteFile(path, data.Bytes(), 0o600); err != nil {
		t.Fatal(err)
	}
	store, err := NewStore(path)
	if err != nil {
		t.Fatal(err)
	}
	stored, err := store.Get(profile.ID)
	if err != nil {
		t.Fatal(err)
	}
	if stored.Slug != "provider-conn-fb0" {
		t.Fatalf("load changed a persisted slug: %q", stored.Slug)
	}
}
